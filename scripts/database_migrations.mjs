// Reproducible baseline. Existing databases adopt the baseline with migration repair;
// they must NEVER execute the legacy baseline over their current schema.
import fs from 'node:fs';import crypto from 'node:crypto';
const root=new URL('../',import.meta.url),manifest=JSON.parse(fs.readFileSync(new URL('supabase/legacy-migrations.json',root)));
const digest=s=>crypto.createHash('sha256').update(s).digest('hex');
const chunks=[];
for(const item of manifest.files){const sql=fs.readFileSync(new URL('supabase/'+item.path,root),'utf8');if(digest(sql)!==item.sha256)throw Error('Historical migration changed: '+item.path);chunks.push('-- LEGACY SOURCE: '+item.path+'\n'+sql.trim());}
const baseline=`-- Generated by scripts/database_migrations.mjs from the immutable legacy manifest.
-- FRESH DATABASES ONLY. Existing deployments: see docs/security_hardening.md.
do $$ begin
 if to_regclass('public.profiles') is not null then
  raise exception 'Existing SPACE schema detected. Do not replay the baseline. Use Supabase migration repair after verifying the legacy manifest.';
 end if;
end $$;
\n`+chunks.join('\n\n')+'\n';
const path=new URL('supabase/migrations/20261027000000_legacy_baseline.sql',root);
if(process.argv.includes('--write')){fs.writeFileSync(path,baseline);console.log('Generated fresh-database baseline.');}
else{if(!fs.existsSync(path)||fs.readFileSync(path,'utf8')!==baseline)throw Error('Baseline does not match manifest. Run node scripts/database_migrations.mjs --write.');console.log('Historical checksums and canonical baseline verified.');}
